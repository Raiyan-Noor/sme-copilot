"""Generate frontend/lib/types.ts from docs/openapi.json, so the frontend types mirror the backend Pydantic models.

`make openapi` regenerates both files; `make test` runs this with --check and fails if types.ts is out of date.
Stdlib only. Covers the JSON Schema subset FastAPI/Pydantic v2 emit: $ref, anyOf, enum, const, arrays, objects
with properties or additionalProperties, and the scalar types.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "docs" / "openapi.json"
OUT = ROOT / "frontend" / "lib" / "types.ts"

HEADER = """\
// GENERATED by scripts/gen_frontend_types.py from docs/openapi.json. Do not edit by hand: run `make openapi`.
// Money is integer minor units. Dates are ISO strings (YYYY-MM-DD).
"""
IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def ts_type(s: dict) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "anyOf" in s:
        parts = []
        for sub in s["anyOf"]:
            t = ts_type(sub)
            if t not in parts:
                parts.append(t)
        return " | ".join(parts)
    t = s.get("type")
    if t == "string":
        return "Blob" if s.get("contentMediaType") == "application/octet-stream" or s.get("format") == "binary" \
            else "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        item = ts_type(s.get("items", {}))
        return f"({item})[]" if "|" in item else f"{item}[]"
    if t == "object" or "properties" in s or "additionalProperties" in s:
        if "properties" in s:
            return inline_object(s)
        extra = s.get("additionalProperties")
        value = ts_type(extra) if isinstance(extra, dict) and extra else "unknown"
        return f"Record<string, {value}>"
    return "unknown"


def inline_object(s: dict) -> str:
    fields = "; ".join(field_line(name, prop, name in s.get("required", [])) for name, prop in s["properties"].items())
    return "{ " + fields + " }"


def field_line(name: str, prop: dict, required: bool) -> str:
    key = name if IDENT.match(name) else json.dumps(name)
    return f"{key}{'' if required else '?'}: {ts_type(prop)}"


def doc_comment(text: str | None, indent: str = "") -> list[str]:
    if not text:
        return []
    lines = text.strip().splitlines()
    if len(lines) == 1:
        return [f"{indent}/** {lines[0].strip()} */"]
    return [f"{indent}/**"] + [f"{indent} * {ln.rstrip()}".rstrip() for ln in lines] + [f"{indent} */"]


def render(spec: dict) -> str:
    out = [HEADER]
    for name, s in sorted(spec["components"]["schemas"].items()):
        out += doc_comment(s.get("description"))
        if "properties" in s:
            out.append(f"export interface {name} {{")
            required = set(s.get("required", []))
            for field, prop in s["properties"].items():
                out += doc_comment(prop.get("description"), "  ")
                out.append(f"  {field_line(field, prop, field in required)};")
            out.append("}")
        else:
            out.append(f"export type {name} = {ts_type(s)};")
        out.append("")
    return "\n".join(out)


def main() -> int:
    text = render(json.loads(SPEC.read_text(encoding="utf-8")))
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date with docs/openapi.json. Run `make openapi`.")
            return 1
        print("Frontend types match docs/openapi.json.")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
